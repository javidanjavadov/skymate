export type Key = keyof typeof en

const DICTS: Record<Language, Record<Key, string>> = { en, az, ru }

/** Translated text for a language; {placeholders} are filled from `values`. */
export function translate(code: Language, key: Key, values?: Record<string, string | number>) {
  const text = DICTS[code][key] ?? en[key] ?? String(key)
  return values ? text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? "")) : text
}

/** The translator for the current language, e.g. t("card.wind"). */
export function useT() {
  const code = useLanguage()
  const t = (key: Key, values?: Record<string, string | number>) => translate(code, key, values)
  return { t, language: code, locale: localeOf(code) }
}
